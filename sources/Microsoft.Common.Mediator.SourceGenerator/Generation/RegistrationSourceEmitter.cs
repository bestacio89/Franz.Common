using Franz.Common.Mediator.SourceGenerator.Discovery;
using System.Collections.Generic;
using System.Text;

namespace Franz.Common.Mediator.SourceGenerator.Generation;

internal static class RegistrationSourceEmitter
{
  public static string Generate(IEnumerable<HandlerInfo> handlers)
  {
    var handlerList = new List<HandlerInfo>(handlers);
    var builder = new StringBuilder();
    var invokers = new StringBuilder();
    var defaultPipelines = new StringBuilder();
    var registeredHandlers = new HashSet<string>();
    var registeredInvokers = new HashSet<string>();
    var registeredTransientImplementations = new HashSet<string>();
    var registeredPipelineServices = new HashSet<string>();

    builder.AppendLine(@"// <auto-generated/>
#nullable enable

using System;
using System.Runtime.CompilerServices;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.DependencyInjection.Extensions;
using Franz.Common.Mediator.Dispatchers;
using Franz.Common.Mediator.Messages;
using Franz.Common.Mediator.Pipelines.Core;
using Franz.Common.Mediator.Pipelines.Logging;
using Franz.Common.Mediator.Pipelines.Validation;
using Franz.Common.Mediator.Pipelines.Transaction;
using Franz.Common.Mediator.Pipelines.Processors;
using Franz.Common.Mediator.Pipelines.Processors.Logging;
using Franz.Common.Mediator.Pipelines.Processors.Validation;
using Franz.Common.Mediator.Registration;

namespace Franz.Common.Mediator.Registration;

internal static class FranzMediatorGeneratedRegistration
{
    [ModuleInitializer]
    internal static void Initialize()
    {
        RegisterInvokers();
        var assembly = typeof(FranzMediatorGeneratedRegistration).Assembly;
        GeneratedHandlerRegistrationRegistry.Register(assembly, RegisterHandlers);
        GeneratedHandlerRegistrationRegistry.RegisterTransient(assembly, RegisterTransientHandlers);
        GeneratedHandlerRegistrationRegistry.RegisterDefaultPipelines(assembly, RegisterDefaultPipelines);
    }

    private static void RegisterHandlers(IServiceCollection services)
    {
        ArgumentNullException.ThrowIfNull(services);
");

    var transientRegistrations = new StringBuilder();

    foreach (var handler in handlerList)
    {
      var registrationKey = $"{handler.ServiceType}|{handler.ImplementationType}";
      if (registeredHandlers.Add(registrationKey))
      {
        builder.AppendLine(
            $"        services.TryAddEnumerable(ServiceDescriptor.Scoped(typeof({handler.ServiceType}), typeof({handler.ImplementationType})));");
        if ((handler.HandlerKind is "Command" or "Query") && registeredTransientImplementations.Add(handler.ImplementationType))
        {
          transientRegistrations.AppendLine(
              $"        services.TryAddEnumerable(ServiceDescriptor.Transient(typeof({handler.ServiceType}), typeof({handler.ImplementationType})));");
        }
      }

      var invokerKey = $"{handler.HandlerKind}|{handler.RequestType}|{handler.ResponseType}";
      if (registeredInvokers.Add(invokerKey))
      {
        switch (handler.HandlerKind)
        {
          case "Command":
            invokers.AppendLine(
                $"        GeneratedMediatorInvokerRegistry.RegisterCommand<{handler.RequestType}, {handler.ResponseType}>();");
            break;
          case "VoidCommand":
            invokers.AppendLine(
                $"        GeneratedMediatorInvokerRegistry.RegisterVoidCommand<{handler.RequestType}>();");
            break;
          case "Query":
            invokers.AppendLine(
                $"        GeneratedMediatorInvokerRegistry.RegisterQuery<{handler.RequestType}, {handler.ResponseType}>();");
            break;
          case "Event":
            invokers.AppendLine(
                $"        GeneratedMediatorInvokerRegistry.RegisterEvent<{handler.RequestType}>();");
            break;
        }
      }

      switch (handler.HandlerKind)
      {
        case "Command":
          AppendRequestPipelineRegistrations(defaultPipelines, registeredPipelineServices,
              $"ICommand<{handler.ResponseType}>", handler.ResponseType, handler.RequestType);
          break;
        case "Query":
          AppendRequestPipelineRegistrations(defaultPipelines, registeredPipelineServices,
              $"IQuery<{handler.ResponseType}>", handler.ResponseType, handler.RequestType);
          break;
        case "VoidCommand":
          AppendRequestPipelineRegistrations(defaultPipelines, registeredPipelineServices,
              "ICommand", "Unit", handler.RequestType);
          break;
        case "Notification":
          AppendNotificationPipelineRegistrations(defaultPipelines, registeredPipelineServices, handler.RequestType);
          break;
      }
    }

    builder.AppendLine(@"    }

    private static void RegisterTransientHandlers(IServiceCollection services)
    {
        ArgumentNullException.ThrowIfNull(services);
");
    builder.Append(transientRegistrations);
    builder.AppendLine(@"    }

    private static void RegisterDefaultPipelines(IServiceCollection services)
    {
        ArgumentNullException.ThrowIfNull(services);
");
    builder.Append(defaultPipelines);
    builder.AppendLine(@"    }

    private static void RegisterInvokers()
    {");
    builder.Append(invokers);
    builder.AppendLine(@"    }
}");

    return builder.ToString();
  }

  private static void AppendRequestPipelineRegistrations(
      StringBuilder builder,
      HashSet<string> registered,
      string requestContract,
      string responseType,
      string concreteRequest)
  {
    var pipelineRequest = requestContract;
    AppendScoped(builder, registered, $"IPipeline<{pipelineRequest}, {responseType}>",
        $"LoggingPipeline<{pipelineRequest}, {responseType}>");
    AppendScoped(builder, registered, $"IPipeline<{pipelineRequest}, {responseType}>",
        $"ValidationPipeline<{pipelineRequest}, {responseType}>");
    AppendScoped(builder, registered, $"IPipeline<{pipelineRequest}, {responseType}>",
        $"SerilogLoggingPipeline<{pipelineRequest}, {responseType}>");
    AppendScoped(builder, registered, $"IPipeline<{pipelineRequest}, {responseType}>",
        $"TransactionPipeline<{pipelineRequest}, {responseType}>");

    AppendScoped(builder, registered, $"IPreProcessor<{concreteRequest}>",
        $"LoggingPreProcessor<{concreteRequest}>");
    AppendScoped(builder, registered, $"IPreProcessor<{concreteRequest}>",
        $"AuditPreProcessor<{concreteRequest}>");
    AppendScoped(builder, registered, $"IPreProcessor<{concreteRequest}>",
        $"SerilogLoggingPreProcessor<{concreteRequest}>");
    AppendScoped(builder, registered, $"IPreProcessor<{concreteRequest}>",
        $"SerilogAuditPreProcessor<{concreteRequest}>");

    AppendScoped(builder, registered, $"IPostProcessor<{concreteRequest}, {responseType}>",
        $"LoggingPostProcessor<{concreteRequest}, {responseType}>");
    AppendScoped(builder, registered, $"IPostProcessor<{concreteRequest}, {responseType}>",
        $"SerilogLoggingPostProcessor<{concreteRequest}, {responseType}>");
    AppendScoped(builder, registered, $"IPostProcessor<{concreteRequest}, {responseType}>",
        $"SerilogAuditPostProcessor<{concreteRequest}, {responseType}>");
  }

  private static void AppendNotificationPipelineRegistrations(
      StringBuilder builder,
      HashSet<string> registered,
      string notificationType)
  {
    AppendScoped(builder, registered, $"INotificationPipeline<{notificationType}>",
        $"NotificationLoggingPipeline<{notificationType}>");
    AppendScoped(builder, registered, $"INotificationPipeline<{notificationType}>",
        $"NotificationValidationPipeline<{notificationType}>");
  }

  private static void AppendScoped(
      StringBuilder builder,
      HashSet<string> registered,
      string serviceType,
      string implementationType)
  {
    var key = $"{serviceType}|{implementationType}";
    if (!registered.Add(key))
      return;

    builder.AppendLine(
        $"        services.TryAddEnumerable(ServiceDescriptor.Scoped(typeof({serviceType}), typeof({implementationType})));");
  }
}
