using Franz.Common.Mediator.SourceGenerator.Discovery;
using System.Collections.Generic;
using System.Text;

namespace Franz.Common.Mediator.SourceGenerator.Generation;

internal static class RegistrationSourceEmitter
{
  public static string Generate(IEnumerable<HandlerInfo> handlers)
  {
    var builder = new StringBuilder();
    var invokers = new StringBuilder();
    var registeredHandlers = new HashSet<string>();
    var registeredInvokers = new HashSet<string>();

    builder.AppendLine(@"// <auto-generated/>
#nullable enable

using System;
using System.Runtime.CompilerServices;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.DependencyInjection.Extensions;
using Franz.Common.Mediator.Registration;

namespace Franz.Common.Mediator.Registration;

internal static class FranzMediatorGeneratedRegistration
{
    [ModuleInitializer]
    internal static void Initialize()
    {
        RegisterInvokers();
        var assembly = typeof(FranzMediatorGeneratedRegistration).Assembly;
        GeneratedHandlerRegistrationRegistry.Register(assembly, RegisterHandlers);
        GeneratedHandlerRegistrationRegistry.RegisterTransient(assembly, RegisterTransientHandlers);
    }

    private static void RegisterHandlers(IServiceCollection services)
    {
        ArgumentNullException.ThrowIfNull(services);
");

    var transientRegistrations = new StringBuilder();

    foreach (var handler in handlers)
    {
      var registrationKey = $"{handler.ServiceType}|{handler.ImplementationType}";
      if (registeredHandlers.Add(registrationKey))
      {
        builder.AppendLine(
            $"        services.TryAddEnumerable(ServiceDescriptor.Scoped(typeof({handler.ServiceType}), typeof({handler.ImplementationType})));");
        if (handler.HandlerKind is "Command" or "Query")
        {
          transientRegistrations.AppendLine(
              $"        services.TryAddEnumerable(ServiceDescriptor.Transient(typeof({handler.ServiceType}), typeof({handler.ImplementationType})));");
        }
      }

      var invokerKey = $"{handler.HandlerKind}|{handler.RequestType}|{handler.ResponseType}";
      if (!registeredInvokers.Add(invokerKey))
        continue;

      switch (handler.HandlerKind)
      {
        case "Command":
          invokers.AppendLine(
              $"        GeneratedMediatorInvokerRegistry.RegisterCommand<{handler.RequestType}, {handler.ResponseType}>();");
          break;
        case "VoidCommand":
          invokers.AppendLine(
              $"        GeneratedMediatorInvokerRegistry.RegisterVoidCommand<{handler.RequestType}>();");
          break;
        case "Query":
          invokers.AppendLine(
              $"        GeneratedMediatorInvokerRegistry.RegisterQuery<{handler.RequestType}, {handler.ResponseType}>();");
          break;
        case "Event":
          invokers.AppendLine(
              $"        GeneratedMediatorInvokerRegistry.RegisterEvent<{handler.RequestType}>();");
          break;
      }
    }

    builder.AppendLine(@"    }

    private static void RegisterTransientHandlers(IServiceCollection services)
    {
        ArgumentNullException.ThrowIfNull(services);
");
    builder.Append(transientRegistrations);
    builder.AppendLine(@"    }

    private static void RegisterInvokers()
    {");
    builder.Append(invokers);
    builder.AppendLine(@"    }
}");

    return builder.ToString();
  }
}
