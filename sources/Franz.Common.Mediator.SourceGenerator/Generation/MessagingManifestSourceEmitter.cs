using Franz.Common.Mediator.SourceGenerator.Discovery;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Franz.Common.Mediator.SourceGenerator.Generation;

internal static class MessagingManifestSourceEmitter
{
  public static string Generate(IEnumerable<string> destinations, IEnumerable<HandlerInfo> handlers)
  {
    var destinationTypes = destinations
        .Distinct(StringComparer.Ordinal)
        .OrderBy(static type => type, StringComparer.Ordinal)
        .ToArray();
    var subscriptionTypes = handlers
        .Where(static handler => handler.HandlerKind == "Notification" && handler.IsIntegrationEvent)
        .Select(static handler => handler.RequestType)
        .Distinct(StringComparer.Ordinal)
        .OrderBy(static type => type, StringComparer.Ordinal)
        .ToArray();

    var builder = new StringBuilder();
    builder.AppendLine(@"// <auto-generated/>
#nullable enable
using System;
using System.Runtime.CompilerServices;
using Franz.Common.Messaging.Manifest;

internal static class FranzMessagingGeneratedManifest
{
    [ModuleInitializer]
    internal static void Register()
    {
        MessagingManifestRegistry.Register(
            typeof(FranzMessagingGeneratedManifest).Assembly,
            new MessagingManifest(
                new Type[]
                {");
    foreach (var type in destinationTypes)
      builder.Append("                    typeof(").Append(type).AppendLine("),");
    builder.AppendLine(@"                },
                new Type[]
                {");
    foreach (var type in subscriptionTypes)
      builder.Append("                    typeof(").Append(type).AppendLine("),");
    builder.AppendLine(@"                }));
    }
}");
    return builder.ToString();
  }
}
